移動(_発, _着, _経) :-
	経由禁止駅指定付移動(_発, _着, [_発, _着], _経).

経由禁止駅指定付移動(_発, _着, _禁, _経) :- 隣(_発, _着), reverse(_禁, [_, _| _経]).
経由禁止駅指定付移動(_発, _着, _禁, _経) :-
	隣(_発, _途), 含まれない(_途, _禁), 経由禁止駅指定付移動(_途, _着, [_途| _禁], _経).

含まれない(X, _経) :-
	駅一覧(_資元), 除去(_資元, X, _資残), 複除去(_資残, _経).

複除去(_, []).
複除去(_資元, [X| _経]) :- 除去(_資元, X, _資残), 複除去(_資残, _経).

除去([X| _資元], X, _資元).
除去([Y| _資元], X, [Y| _資残]) :- 除去(_資元, X, _資残).

指定個以下([], _).
指定個以下([_| X], N) :- N > 0, N1 is N - 1, 指定個以下(X, N1).

